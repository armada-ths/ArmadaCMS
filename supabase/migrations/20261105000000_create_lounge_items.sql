CREATE TABLE public.lounge_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    name_sv TEXT,
    description TEXT,
    description_sv TEXT,
    image_url TEXT,
    sort_order BIGINT NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 9007199254740991),
    max_per_order BIGINT CHECK (max_per_order BETWEEN 1 AND 9007199254740991),
    sold_out BOOLEAN NOT NULL DEFAULT false
);

CREATE INDEX lounge_items_display_order_idx ON public.lounge_items (sort_order, id);
ALTER TABLE public.lounge_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.lounge_items FROM anon, authenticated;
GRANT ALL ON public.lounge_items TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.lounge_items_id_seq TO service_role;
