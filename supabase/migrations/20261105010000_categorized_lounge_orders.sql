-- The approved catalogue reset intentionally discards existing lounge items.
DELETE FROM public.lounge_items;
CREATE TABLE public.lounge_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    name_sv TEXT,
    sort_order BIGINT NOT NULL DEFAULT 0 CHECK (sort_order >= 0)
);
ALTER TABLE public.lounge_items DROP COLUMN image_url;
ALTER TABLE public.lounge_items ADD COLUMN category_id BIGINT NOT NULL
    REFERENCES public.lounge_categories(id) ON DELETE CASCADE;
CREATE INDEX lounge_items_category_order_idx ON public.lounge_items(category_id, sort_order, id);
CREATE TABLE public.lounge_catalogue_state (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    revision BIGINT NOT NULL DEFAULT 0
);
INSERT INTO public.lounge_catalogue_state(id) VALUES (1);
CREATE TABLE public.lounge_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    company_id BIGINT NOT NULL,
    company_name TEXT NOT NULL,
    is_test BOOLEAN NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'completed', 'cancelled')),
    idempotency_key TEXT NOT NULL,
    fingerprint TEXT NOT NULL,
    delivery_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (delivery_status IN ('pending', 'sending', 'sent', 'failed', 'unknown')),
    delivery_error TEXT NOT NULL DEFAULT '',
    claim_token TEXT NOT NULL DEFAULT '',
    claim_expires_at TIMESTAMPTZ,
    UNIQUE (is_test, idempotency_key)
);
CREATE TABLE public.lounge_order_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.lounge_orders(id) ON DELETE CASCADE,
    item_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    item_name TEXT NOT NULL,
    item_name_sv TEXT,
    category_name TEXT NOT NULL,
    category_name_sv TEXT,
    quantity BIGINT NOT NULL CHECK (quantity BETWEEN 1 AND 9007199254740991),
    position INTEGER NOT NULL CHECK (position >= 0),
    UNIQUE (order_id, item_id)
);
CREATE INDEX lounge_orders_list_idx ON public.lounge_orders(is_test, status, id DESC);
CREATE INDEX lounge_orders_company_idx ON public.lounge_orders(company_id);
CREATE INDEX lounge_order_lines_category_idx ON public.lounge_order_lines(category_id, order_id);
CREATE INDEX lounge_order_lines_item_idx ON public.lounge_order_lines(item_id, order_id);
ALTER TABLE public.lounge_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lounge_catalogue_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lounge_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lounge_order_lines ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.lounge_categories, public.lounge_catalogue_state,
    public.lounge_orders, public.lounge_order_lines FROM anon, authenticated;
GRANT ALL ON public.lounge_categories, public.lounge_catalogue_state,
    public.lounge_orders, public.lounge_order_lines TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.lounge_categories_id_seq,
    public.lounge_orders_id_seq, public.lounge_order_lines_id_seq TO service_role;
